def material(c):
    r, g, b = c
    return (f'<material><ambient>{r * 0.7:.3f} {g * 0.7:.3f} {b * 0.7:.3f} 1</ambient>'
            f'<diffuse>{r:.3f} {g:.3f} {b:.3f} 1</diffuse><specular>0.05 0.05 0.05 1</specular></material>')


def model_sdf(name, boxes):
    parts = []
    for b in boxes:
        pose = f'{b["cx"]:.4f} {b["cy"]:.4f} {0.5 * b["h"]:.4f} 0 0 {b["yaw"]:.5f}'
        geom = f'<geometry><box><size>{b["sx"]:.4f} {b["sy"]:.4f} {b["h"]:.4f}</size></box></geometry>'
        parts.append(f'      <collision name="{b["name"]}_c"><pose>{pose}</pose>{geom}</collision>\n'
                     f'      <visual name="{b["name"]}_v"><pose>{pose}</pose>{geom}{material(b["color"])}</visual>')
    body = '\n'.join(parts)
    return (f'<?xml version="1.0"?>\n<sdf version="1.9">\n  <model name="{name}">\n    <static>true</static>\n'
            f'    <!-- generated by tools/generate_world.py from tools/layout.py; poses are in the world frame '
            f'(include at pose 0 0 0) -->\n    <link name="link">\n{body}\n    </link>\n  </model>\n</sdf>\n')


